#!/bin/bash
# 「**本次**起跑之后」的日志里有没有 ALLDONE。退出 0 = 本批已完成。
#
# 存在的理由:日志是追加的(start_run.sh 用 >> 而不是 >,见那里的注释),
# 于是上一次跑留下的 ALLDONE 会让存活检测在新批刚起来时当场判「完成」,
# 而它一 break,**卡死检测和进程消失检测就跟着一起没了** —— 又回到那个
# "沉默既是正常也是全死了"的状态。
# 2026-09-13 实测:同一日志先跑 1 条 smoke 再起全批,监视器立刻报
# 「✅ 生成完成 11/73」,此后整批无人看守。
#
# 起跑标记由 start_run.sh 写入,形如 `=== 起跑 2026-09-13 06:12:00 commit abc123 jobs=... ===`。
# 日志不存在 → awk 报错退出非 0 = 「未完成」,正是想要的。
awk '/^=== 起跑 /{seen=0} /ALLDONE/{seen=1} END{exit !seen}' "$1"
